from __future__ import annotations

import csv
import glob
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request
import uuid
import zipfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DENOVO = ROOT / "denovo"
TARGETS = DENOVO / "targets"
OUT = ROOT / "results" / "denovo"
JOBS = OUT / "jobs"
DESIGN_DIR = OUT / "designs"
for _p in (OUT, JOBS, DESIGN_DIR):
    _p.mkdir(parents=True, exist_ok=True)

DESIGN_COLS = ["design_id", "parent_id", "generator", "framework", "seed", "hotspot_set", "vhh_seq", "cdr1", "cdr2",
               "cdr3", "cdr_scheme", "design_cif", "job_id", "params_json", "created_utc"]
AA = set("ACDEFGHIKLMNPQRSTVWY")
BASE = os.environ.get("JAPANFOLD_BASE_URL", "https://api.japanfold.aiand.com")


def utcnow() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def targets_ready() -> bool:
    return (TARGETS / "READY").exists()


def wait_targets(timeout_s: int = 1800) -> None:
    t0 = time.time()
    while not targets_ready():
        if time.time() - t0 > timeout_s:
            sys.exit("denovo/targets/READY did not appear")
        time.sleep(10)


def safe_id(s: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_.-]+", "-", s).strip("-")
    return s[:48]


def read_csv(path) -> list[dict]:
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def write_csv(path, rows: list[dict], cols: list[str] | None = None) -> None:
    rows = list(rows)
    cols = cols or (list(rows[0].keys()) if rows else [])
    tmp = str(path) + ".tmp"
    with open(tmp, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    os.replace(tmp, path)  # atomic: readers never see half a file


def load_designs(include_controls: bool = True) -> list[dict]:
    """All designs from results/denovo/designs_*.csv, de-duplicated by design_id (first file wins)."""
    seen, out = set(), []
    for f in sorted(glob.glob(str(OUT / "designs_*.csv"))):
        for r in read_csv(f):
            if r["design_id"] in seen:
                continue
            if not include_controls and r.get("generator") == "control":
                continue
            seen.add(r["design_id"])
            out.append(r)
    return out


def check_seq(seq: str) -> str | None:
    """Return None if the sequence is plain VHH-like text, else a reason."""
    if not seq or set(seq) - AA:
        return "non-standard characters"
    if not 90 <= len(seq) <= 160:
        return f"length {len(seq)} outside 90-160"
    return None


# ---------------------------------------------------------------- job cache (never pay twice)
def cached_job(name: str) -> str | None:
    f = JOBS / f"{safe_id(name)}.json"
    return json.loads(f.read_text())["job_id"] if f.exists() else None


def save_job(name: str, job_id: str, **meta) -> None:
    (JOBS / f"{safe_id(name)}.json").write_text(json.dumps({"job_id": job_id, "ts": utcnow(), **meta}, indent=1))


# ---------------------------------------------------------------- JapanFold client
class JapanFold:
    def __init__(self):
        key = os.environ.get("JAPANFOLD_API_KEY")
        if not key:
            sys.exit("JAPANFOLD_API_KEY not set")
        self._h = {"X-JapanFold-Client": "skill", "Authorization": f"Bearer {key}"}

    def call(self, method: str, path: str, body=None, headers=None, timeout: int = 120):
        h = dict(self._h)
        if body is not None:
            h["Content-Type"] = "application/json"
        h.update(headers or {})
        req = urllib.request.Request(BASE + path, data=json.dumps(body).encode() if body is not None else None,
                                     headers=h, method=method)
        try:
            with urllib.request.urlopen(req, timeout=timeout) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            detail = e.read().decode(errors="replace")[:600]
            raise RuntimeError(f"HTTP {e.code} on {method} {path}: {detail}") from None

    def credits(self) -> float:
        return json.loads(self.call("GET", "/v1/credits"))["balance"]

    def models(self) -> dict:
        return json.loads(self.call("GET", "/v1/models"))

    def submit(self, name: str, path: str, body: dict) -> str:
        """POST once per `name`: a repeat returns the cached job id and costs nothing."""
        jid = cached_job(name)
        if jid:
            return jid
        raw = self.call("POST", path, body, {"Idempotency-Key": str(uuid.uuid5(uuid.NAMESPACE_URL, name))})
        job = json.loads(raw)
        if "id" not in job:
            raise RuntimeError(f"submit failed: {job.get('detail') or str(job)[:400]}")
        save_job(name, job["id"], path=path, warnings=job.get("warnings"))
        return job["id"]

    def wait(self, job_id: str, poll_s: int = 3, max_s: int = 3600, log=print) -> dict:
        t0, last = time.time(), None
        while True:
            j = json.loads(self.call("GET", f"/v1/jobs/{job_id}", headers={"Prefer": "wait=60"}, timeout=150))
            st = j.get("status")
            if st != last:
                log(f"[{job_id}] {st}" + (f" queue={json.dumps(j['queue'])[:160]}" if j.get("queue") else ""))
                last = st
            if st in ("succeeded", "failed", "canceled"):
                return j
            if time.time() - t0 > max_s:
                raise TimeoutError(f"job {job_id} still {st} after {max_s}s; resume later with the same name")
            time.sleep(poll_s)

    def results(self, job_id: str) -> dict:
        return json.loads(self.call("GET", f"/v1/jobs/{job_id}/results"))

    def download(self, job_id: str, dest: Path) -> Path:
        """Fetch the archive and extract it with a path-traversal check."""
        dest = Path(dest)
        dest.mkdir(parents=True, exist_ok=True)
        z = dest / f"{job_id}.zip"
        z.write_bytes(self.call("GET", f"/v1/jobs/{job_id}/archive", timeout=300))
        root = dest.resolve()
        with zipfile.ZipFile(z) as zf:
            for m in zf.infolist():
                t = (dest / m.filename).resolve()
                if t != root and not str(t).startswith(str(root) + os.sep):
                    raise RuntimeError(f"unsafe path in archive: {m.filename}")
            zf.extractall(dest)
        return dest
