"""Write the panel out so someone else can audit it.

Two files: a CSV to sort, and a markdown note that says what every column
means, what the control scored, and what was thrown away and why. The run id
is on every row -- a number without a run id cannot be checked, and "show
where each score came from" is the one thing the organisers asked for
explicitly.

The ranking is a documented ordering, not a predictor. It says "look at these
first", and the components are printed next to it so a reader can disagree
with the weighting without having to rerun anything.
"""
import csv
import os

from . import config

COLUMNS = ["rank", "name", "confidence", "ptm", "contacts", "interface_residues",
           "epitope_overlap", "epitope_shared", "penalty", "pI", "gravy",
           "length", "cdr3", "op", "structure", "sequence"]


def composite(row, control=None):
    """Interface size first, agreement second, developability as a tie-break.

    Contacts carry the most weight because they are measured from coordinates
    rather than reported by the model, and because Boltz2 gives no ipTM, so
    confidence alone cannot distinguish a confident monomer from a confident
    complex. Normalised against the control where there is one, so the number
    reads as "fraction of a known binder".
    """
    contacts = row.get("contacts") or 0
    ref = (control or {}).get("contacts") or 0
    contact_term = (contacts / float(ref)) if ref else (contacts / 200.0)
    conf = row.get("confidence") or 0.0
    ptm = row.get("ptm") or 0.0
    overlap = row.get("epitope_overlap") or 0.0
    penalty = row.get("penalty") or 0.0
    return round(1.6 * contact_term + 1.0 * conf + 0.6 * ptm + 0.8 * overlap
                 - 0.05 * penalty, 4)


def write(state, work_dir):
    results = os.path.join(work_dir, config.RESULTS_DIR)
    os.makedirs(results, exist_ok=True)
    control = state.get("control_score") or {}
    rows = list(state.get("scores") or [])
    for r in rows:
        r["score"] = composite(r, control)
        r["length"] = len(r.get("sequence") or "")
    rows.sort(key=lambda r: -r["score"])
    for i, r in enumerate(rows, 1):
        r["rank"] = i

    csv_path = os.path.join(results, "ranking.csv")
    with open(csv_path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["score"] + COLUMNS, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow(r)

    md_path = os.path.join(results, "report.md")
    with open(md_path, "w") as fh:
        fh.write(_markdown(state, rows, control))
    return csv_path, md_path


def _markdown(state, rows, control):
    out = []
    out.append("# De novo panel against %s\n" % config.TARGET_NAME)
    out.append("Generated by `python3 -m denovo`. Every row carries the run id "
               "that produced it, so any number here can be re-fetched with "
               "`forge.py fetch <op> --dest <dir>`.\n")

    ep = state.get("reference_epitope") or []
    if ep:
        out.append("**Reference epitope.** Measured from %s by taking every %s residue "
                   "within 4.5 A of a trastuzumab heavy-atom: %d residues. Epitope "
                   "overlap below is the Jaccard overlap of a candidate's interface "
                   "with that set.\n" % (config.TARGET_PDB.upper(), config.TARGET_NAME, len(ep)))

    if control.get("contacts"):
        out.append("**Control.** Trastuzumab co-folded against the same target, scored the "
                   "same way: confidence %s, pTM %s, %s heavy-atom contacts. Contact counts "
                   "below are normalised against this, so 1.0 means \"as large an interface "
                   "as a known binder\".\n"
                   % (control.get("confidence"), control.get("ptm"), control.get("contacts")))
    else:
        out.append("**No control was scored**, so the contact counts below are absolute and "
                   "there is nothing to calibrate them against. Treat the ranking as "
                   "relative only.\n")

    out.append("## Panel\n")
    out.append("| rank | candidate | score | conf | pTM | contacts | iface res | "
               "epitope overlap | dev. penalty | pI | run id |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | `%s` |" % (
            r.get("rank"), r.get("name"), r.get("score"), r.get("confidence"),
            r.get("ptm"), r.get("contacts"), r.get("interface_residues"),
            r.get("epitope_overlap"), r.get("penalty"), r.get("pI"), r.get("op")))
    out.append("")

    dropped = state.get("dropped") or []
    if dropped:
        out.append("## Not carried forward\n")
        out.append("Dropped before any GPU time was spent on them.\n")
        out.append("| candidate | reason | penalty |")
        out.append("|---|---|---|")
        for a in dropped:
            reason = ", ".join(a.get("blocking") or []) or "ranked below the cut"
            out.append("| %s | %s | %s |" % (a.get("name"), reason, a.get("penalty")))
        out.append("")

    out.append("## How to read this\n")
    out.append("- **conf / pTM** come from Boltz2. There is no ipTM in its output, so "
               "neither number is interface-specific: a confident, well-formed monomer "
               "next to a target scores well on both.\n")
    out.append("- **contacts / iface res** are measured from the returned coordinates "
               "(heavy atoms within 4.5 A across chains). This is the part of the score "
               "that is actually about the interface.\n")
    out.append("- **epitope overlap** asks whether the candidate lands where trastuzumab "
               "lands. Low overlap is not failure; it may be a different and useful "
               "epitope. It is information, not a verdict.\n")
    out.append("- **dev. penalty** is sequence liabilities weighted by region "
               "(CDR3 > CDR1/2 > framework). Lower is better.\n")
    out.append("- **score** is the documented weighting in `report.composite`. It is an "
               "ordering to triage by, not an affinity prediction. Nothing in this "
               "pipeline predicts affinity.\n")

    out.append("## Limits\n")
    out.append("- A co-fold is not a binding assay. Two models agreeing that a complex is "
               "plausible is weak evidence of binding and no evidence of affinity.\n")
    out.append("- CDR1 and CDR2 are only labelled when AntiFold returns its region CSV; "
               "otherwise the liability scan treats them as framework and under-counts.\n")
    out.append("- The control calibrates the *scoring*, not the *design*: trastuzumab is "
               "an IgG Fab, the candidates are single-domain VHHs, and a smaller paratope "
               "makes a smaller interface before any question of quality.\n")
    out.append("- Not for clinical use.\n")
    return "\n".join(out)
