"""One table for the ten submitted candidates, on the three judged axes.

WHAT THIS IS FOR
  The jury is told to count, per design, how many of three measured properties
  beat trastuzumab: affinity (SPR), epitope preservation (competitive binding)
  and thermostability. The lab measures those weeks after the event. This table
  states, for each candidate, what we expect on each axis, how uncertain that
  expectation is, and what it rests on.

  Every cell is labelled. `measured` means measured on this exact molecule.
  `predicted` means a model said so. `literature` means someone measured it on
  a different molecule. Nothing in the three judged columns is `measured`,
  because nobody has run the assay yet, and the table says so rather than
  letting a confident number imply otherwise.

SOURCES
  results/gate/novelty_full.csv   exhaustive novelty distance (measured, exact)
  results/epitope/epitope.csv     Boltz-2 contact overlap vs trastuzumab
  results/r66g/pairs.csv          +/- R66G matched pairs, epitope and interface
  results/stabilise/stab_liab.json  official checker liability motifs
  results/SUBMISSION.csv          the submitted rows

USAGE
  python scripts/candidate_table.py --out results/CANDIDATES.md
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# The one quantitative claim behind every -stab row, and its provenance.
R66G_DTM = "+4.9 C"
R66G_CITE = "Okazaki 2023, ACS Omega 8(25):22945, scFv, DSF"
R66G_KD = "2.0 -> 4.8 nM (same paper, SPR)"
CARTER_CITE = "Carter 1992 PNAS: VL66 Gly->Arg gained 4x affinity (4.4 -> 1.1 nM, IgG)"


def load_epitope(path: Path) -> dict[str, list[float]]:
    """design -> [overlap vs trastuzumab, per Boltz-2 seed]."""
    out: dict[str, list[float]] = {}
    if not path.exists():
        return out
    for r in csv.DictReader(path.open()):
        if not r["model"].startswith("boltz2"):
            continue
        v = r["overlap_vs_tz_same_model"]
        if v:
            out.setdefault(r["id"], []).append(float(v))
    return out


def load_r66g(path: Path):
    """base design -> (median epitope pair overlap, median iptm delta, n seeds)."""
    out = {}
    if not path.exists():
        return out
    rows = list(csv.DictReader(path.open()))
    for base in sorted({r["id"] for r in rows}):
        mine = [r for r in rows if r["id"] == base]
        ov = statistics.median(float(r["pair_overlap"]) for r in mine)
        ds = [
            float(r["iptm_ab_ag_stab"]) - float(r["iptm_ab_ag_wt"])
            for r in mine
            if r["iptm_ab_ag_stab"] and r["iptm_ab_ag_wt"]
        ]
        out[base] = (ov, statistics.median(ds) if ds else None, len(mine))
    return out


def load_liabilities(path: Path) -> dict[str, tuple[int, int]]:
    """id -> (total motifs, high-severity motifs)."""
    out: dict[str, tuple[int, int]] = {}
    if not path.exists():
        return out
    for row in json.loads(path.read_text()):
        libs = row.get("liabilities", [])
        out[row["sequence_id"]] = (
            len(libs), sum(1 for l in libs if l.get("severity") == "high")
        )
    return out


def fmt(vals: list[float]) -> str:
    if not vals:
        return "-"
    if len(vals) == 1:
        return f"{vals[0]:.2f} (1 seed)"
    return f"{statistics.median(vals):.2f} (±{(max(vals)-min(vals))/2:.2f}, {len(vals)} seeds)"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--submission", type=Path, default=ROOT / "results/SUBMISSION.csv")
    ap.add_argument("--epitope", type=Path, default=ROOT / "results/epitope/epitope.csv")
    ap.add_argument("--r66g", type=Path, default=ROOT / "results/r66g/pairs.csv")
    ap.add_argument("--novelty", type=Path, default=ROOT / "results/gate/novelty_full.csv")
    ap.add_argument(
        "--liabilities", type=Path, default=ROOT / "results/stabilise/stab_liab.json"
    )
    ap.add_argument("--out", type=Path, default=ROOT / "results/CANDIDATES.md")
    args = ap.parse_args(argv)

    rows = list(csv.DictReader(args.submission.open()))
    epi = load_epitope(args.epitope)
    r66g = load_r66g(args.r66g)
    liab = load_liabilities(args.liabilities)
    novel = {r["sequence_id"]: r for r in csv.DictReader(args.novelty.open())} \
        if args.novelty.exists() else {}

    tz_liab = liab.get("trastuzumab", (8, 3))

    L = [
        "# The ten candidates, on the three judged axes",
        "",
        "Generated by `scripts/candidate_table.py`. **Nothing in the three judged",
        "columns is a laboratory measurement.** The lab measures affinity (SPR),",
        "epitope preservation (competitive binding) and thermostability after the",
        "event. Every cell below is labelled with what kind of claim it is.",
        "",
        "| Label | Meaning |",
        "| --- | --- |",
        "| `measured` | measured on this exact molecule |",
        "| `predicted` | a model's output, with its own noise floor quoted |",
        "| `literature` | measured by someone else, on a different molecule |",
        "| `unknown` | we have no basis for a claim, and do not make one |",
        "",
        "## The table",
        "",
        "| # | Candidate | R66G | Affinity (SPR) | Epitope | Thermostability | Main uncertainty |",
        "| ---: | --- | :---: | --- | --- | --- | --- |",
    ]

    for i, r in enumerate(rows, 1):
        sid = r["sequence_id"]
        base = sid.replace("-stab", "")
        stab = sid.endswith("-stab")
        ep = fmt(epi.get(base, []))

        if stab:
            pair = r66g.get(base)
            if pair:
                ov, d, n = pair
                ep_cell = (f"`predicted` {ep}; R66G pair overlap {ov:.2f} "
                           f"({n} seeds, noise floor 0.97)")
                aff_cell = (f"`literature` R66G costs affinity: {R66G_KD}. "
                            f"`predicted` interface pTM {d:+.3f} vs parent"
                            if d is not None else f"`literature` {R66G_KD}")
            else:
                ep_cell = f"`predicted` {ep} (parent; -stab not folded)"
                aff_cell = f"`literature` R66G costs affinity: {R66G_KD}"
            th_cell = f"`literature` {R66G_DTM} ({R66G_CITE})"
            unc = ("R66G ΔTm is one lab, one format, never replicated, and its "
                   "own paper reports 2.4x weaker KD")
        else:
            ep_cell = f"`predicted` {ep}"
            aff_cell = "`unknown` no scorer we have orders designs at 4 mutations"
            th_cell = "`unknown` loop changes may help or hurt; no deliberate gain"
            unc = "no thermostability gain engineered, so that axis is a coin flip"

        nov = novel.get(sid, {})
        if nov:
            unc += f"; novelty margin {nov['min_distance_to_provided']}/3 (exact)"

        tot, high = liab.get(sid, liab.get(base, (None, None)))
        if tot is not None:
            unc += f"; liabilities {tot} vs trastuzumab {tz_liab[0]}"

        L.append(
            f"| {i} | `{sid}` | {'yes' if stab else 'no'} | {aff_cell} | "
            f"{ep_cell} | {th_cell} | {unc} |"
        )

    L += [
        "",
        "## How to read each column",
        "",
        "**Affinity.** All ten designs carry exactly 4 CDR-H3 mutations. Edit",
        "distance is the only scorer that tracked measured affinity in our",
        "benchmark (Spearman +0.23 in the legal zone), and it is constant across",
        "these ten, so it orders nothing. StaB-ddG was tested on 60 variants whose",
        "KD is known: it reaches +0.38 overall but **+0.14, CI [-0.26, +0.53], at",
        "the 4-5 mutation count our designs sit at** (`results/stabddg/ANALYSIS.md`).",
        "We therefore do not rank these ten on binding and do not pretend to.",
        "",
        "**Epitope.** Boltz-2 contact overlap against Boltz-2's own trastuzumab",
        "prediction. The same sequence folded at two seeds reproduces its own",
        "epitope at median Jaccard 0.97, so differences below ~0.03 are noise.",
        "",
        "**Thermostability.** For the `-stab` rows this is a single literature",
        f"value: {R66G_DTM} on a trastuzumab scFv ({R66G_CITE}). It has not been",
        "measured on our molecules and it has never been independently replicated.",
        "",
        "## The R66G trade, stated plainly",
        "",
        "Six of the ten rows carry one light-chain change, VL R66G. It is the only",
        "thermostability claim in the submission, and it is not free:",
        "",
        f"1. **The source paper reports the cost itself.** {R66G_KD} -- a 2.4x loss,",
        "   error bars that do not overlap, no n and no statistical test. The",
        "   authors describe this as 'unchanged'; their own table does not support",
        "   that word.",
        f"2. **An independent group engineered the residue in the other direction.**",
        f"   {CARTER_CITE}. Trastuzumab has Arg66 on purpose.",
        "3. **The structural premise is wrong.** The mutation is justified on the",
        "   grounds that position 66 is away from the binding site. Measured in",
        "   1N8Z (`results/r66g/R66_GEOMETRY.md`): Arg66's side chain hydrogen-bonds",
        "   CDR-L1 Asn30 at **2.54 A** and sits **5.45 A** from HER2. It is holding",
        "   a loop that contacts the antigen at 2.99 A.",
        "4. **Our own folding agrees in direction.** Across the matched pairs the",
        "   antibody-antigen interface pTM is lower with R66G in 6 of 8 comparisons;",
        "   for trastuzumab itself the drop clears the seed noise floor in both",
        "   seeds. The epitope is preserved (`results/r66g/R66G.md`).",
        "",
        "**Consequence for tiering.** The brief counts a property only if it beats",
        "the measured trastuzumab baseline -- 'ties and regressions are hollow'. A",
        "design carrying R66G is therefore buying the thermostability vertex while",
        "putting the affinity vertex at risk. That is a defensible bet for A-tier",
        "and a poor one for S-tier, which is why the submission does not place it",
        "on every candidate.",
        "",
    ]

    args.out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[:40]))
    print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
